"""Fetch one year's STA scaled score conversion tables (KS1 or KS2) from GOV.UK into its own seed.

Usage:
    uv run python scripts/build_conversion_seed.py ks2 2026
    uv run python scripts/build_conversion_seed.py ks1 2026

Reads the GOV.UK Content API (JSON wrapping the page HTML) and writes
seeds/scaled_scores/seed_scaled_scores_<ks>_<year>.csv, plus the page body to ai/sources/ for
provenance. Then regenerates models/staging/stg_scaled_score_conversion.sql as a union of every
seed in that folder (dbt can't list a folder at parse time, so the refs are written out here).
"""

import csv
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED_DIR = ROOT / "seeds" / "scaled_scores"
UNION_MODEL = ROOT / "models" / "staging" / "stg_scaled_score_conversion.sql"
COLUMNS = ["key_stage", "test_year", "test_name", "raw_score", "scaled_score", "max_raw_score",
           "min_raw_for_scaled_score", "min_scaled_score", "published_date"]

# Per key stage: the GOV.UK publication, full marks per test (fixed since 2016) and the scale.
KEY_STAGES = {
    "ks1": {"path": "/government/publications/optional-key-stage-1-tests-{year}-scaled-scores",
            "max_raw": {"gps": 40, "maths": 60, "reading": 40}, "scale": (85, 115)},
    "ks2": {"path": "/government/publications/key-stage-2-tests-{year}-scaled-scores",
            "max_raw": {"gps": 70, "maths": 110, "reading": 50}, "scale": (80, 120)},
}


def get_json(path):
    with urllib.request.urlopen("https://www.gov.uk/api/content" + path, timeout=30) as resp:
        return json.load(resp)


def heading_to_test(heading):
    h = heading.lower()
    return "gps" if "grammar" in h else "reading" if "reading" in h else "maths"


def fetch_tables(ks, year):
    pub = get_json(KEY_STAGES[ks]["path"].format(year=year))
    [html_path] = [a["url"] for a in pub["details"]["attachments"] if a["attachment_type"] == "html"]
    body = get_json(html_path)["details"]["body"]
    # first_published_at is UK local time with offset, so its date part is the UK publication date.
    published_date = pub["first_published_at"][:10]

    (ROOT / "ai" / "sources").mkdir(parents=True, exist_ok=True)
    (ROOT / "ai" / "sources" / f"{ks}_scaled_scores_{year}.html").write_text(body, encoding="utf-8")

    # Body is a sequence of <h2>Test name</h2><table>...</table>; split on the headings.
    tables = {}
    parts = re.split(r"<h2[^>]*>(.*?)</h2>", body)
    for heading, section in zip(parts[1::2], parts[2::2]):
        rows = []
        for raw, scaled in re.findall(r"<td>\s*([\d\s–-]+?)\s*</td>\s*<td>\s*(.*?)\s*</td>", section):
            lo, _, hi = re.sub(r"\s", "", raw).replace("–", "-").partition("-")
            for r in range(int(lo), int(hi or lo) + 1):  # some years group "0 - 2" into one row
                rows.append((r, int(scaled) if scaled.isdigit() else None))
        tables[heading_to_test(heading)] = rows
    return tables, published_date


def check(ks, tables):
    max_raw = KEY_STAGES[ks]["max_raw"]
    low, high = KEY_STAGES[ks]["scale"]
    assert sorted(tables) == sorted(max_raw), f"tests found: {sorted(tables)}"
    for test, rows in tables.items():
        scores = [s for _, s in rows if s is not None]
        assert [r for r, _ in rows] == list(range(max_raw[test] + 1)), f"{test}: raw marks not 0-{max_raw[test]}"
        assert scores == sorted(scores) and low <= scores[0] and scores[-1] == high, f"{test}: bad scores"
        expected = next(r for r, s in rows if s is not None and s >= 100)
        print(f"{test}: expected standard (100) at raw {expected}")


def main():
    ks, year = sys.argv[1].lower(), int(sys.argv[2])
    tables, published_date = fetch_tables(ks, year)
    check(ks, tables)

    out = SEED_DIR / f"seed_scaled_scores_{ks}_{year}.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(COLUMNS)
        for test in sorted(tables):
            min_raw = next(r for r, s in tables[test] if s is not None)
            for raw, scaled in tables[test]:
                writer.writerow([ks.upper(), year, test, raw, "" if scaled is None else scaled,
                                 KEY_STAGES[ks]["max_raw"][test], min_raw, KEY_STAGES[ks]["scale"][0],
                                 published_date])
    print(f"wrote {out.relative_to(ROOT)} (published {published_date})")
    write_union_model()


def write_union_model():
    seeds = sorted(p.stem for p in SEED_DIR.glob("seed_scaled_scores_*.csv"))
    columns = ",\n".join(f"    {c}" for c in COLUMNS)
    selects = "\nUNION ALL\n".join(f"SELECT\n{columns}\nFROM {{{{ ref('{s}') }}}}" for s in seeds)
    UNION_MODEL.write_text(
        "-- Generated by scripts/build_conversion_seed.py from every seed in\n"
        "-- seeds/scaled_scores/. Don't edit by hand; re-run the script.\n"
        f"{selects}\n", encoding="utf-8")
    print(f"wrote {UNION_MODEL.relative_to(ROOT)} ({len(seeds)} tables)")


if __name__ == "__main__":
    main()
